// ---------- DAR-276: drain the Claude auto-memory folder into the graph ----------
//
// Claude Code writes auto-memory files (its own convention: settings.json's
// `autoMemoryDirectory`) into config.memoryInboxDir regardless of what this codebase thinks
// memory is. This module is the drain: watch that directory, turn each new/changed `*.md`
// into a POST /api/memory/remember on THIS server's own port (config.port), and delete the
// file once it lands. That is the whole contract.
//
// NOTHING ELSE MAY EVER TREAT THIS DIRECTORY AS A SOURCE OF TRUTH. A file sitting here is
// either brand new (not drained yet) or stuck (drain failed and is retried on the next scan)
// — never "the record". The graph (via /api/memory/remember and /api/memory/recall) is the
// only source of truth. `MEMORY.md` in this directory is generated by the index route
// (DAR-280) for Claude's own startup read; if one exists here, this module leaves it alone
// and never drains it.
//
// Deliberately talks to api.ts over plain HTTP on config.port rather than importing anything
// from it — api.ts is owned by another builder (DAR-282's counterpart) and this module must
// not create a code dependency in either direction.
//
// Failure handling: on a non-2xx (or a network error) the file is left in place and logged
// ONCE for that attempt; it is retried whichever scan/watch event notices it next, so nothing
// is ever silently lost. A successful POST (2xx) deletes the file immediately.

import fs from 'node:fs';
import path from 'node:path';
import { config } from '@darbar/core';

const MEMORY_INDEX_FILE = 'MEMORY.md';

// The graph's node types (packages/core/src/types.ts MEMORY_NODE_TYPES). Auto-memory's
// `metadata.type` values (user/feedback/project/reference/...) don't line up one-to-one, so
// each gets mapped to whichever graph type is the closest semantic fit:
//   user      -> preference  (a standing fact about how Raj/the user wants things done)
//   feedback  -> gotcha      (a lesson learned from something going wrong)
//   project   -> project     (exact match)
//   reference -> decision    (closest available: a settled fact/consideration worth recording,
//                             same as a decision node once it's written down — there is no
//                             'reference' or 'note' type in MEMORY_NODE_TYPES)
// Anything else unrecognized falls back to the same 'decision' bucket as reference, logged.
const AUTO_MEMORY_TYPE_MAP: Record<string, string> = {
  user: 'preference',
  feedback: 'gotcha',
  project: 'project',
  reference: 'decision',
};
const AUTO_MEMORY_TYPE_FALLBACK = 'decision';

interface ParsedMemoryFile {
  name: string;
  description: string;
  type: string;
  project: string | undefined;
  body: string;
}

// ---------- minimal frontmatter parser ----------
// Scoped ONLY to the shape Claude Code's auto-memory actually writes (see MEMORY.md-adjacent
// topic files under ~/.claude/projects/*/memory/*.md): a top-level `---` block of `key: value`
// lines plus one nested `metadata:` block indented two spaces, values optionally quoted. This
// is not a general YAML parser and does not try to be one.
function stripQuotes(v: string): string {
  const t = v.trim();
  if ((t.startsWith('"') && t.endsWith('"')) || (t.startsWith("'") && t.endsWith("'"))) {
    return t.slice(1, -1);
  }
  return t;
}

function parseFrontmatter(raw: string): { top: Record<string, string>; meta: Record<string, string>; body: string } {
  const lines = raw.split('\n');
  if (lines[0]?.trim() !== '---') return { top: {}, meta: {}, body: raw };
  let end = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i]?.trim() === '---') { end = i; break; }
  }
  if (end === -1) return { top: {}, meta: {}, body: raw };

  const top: Record<string, string> = {};
  const meta: Record<string, string> = {};
  let inMeta = false;
  for (const line of lines.slice(1, end)) {
    if (/^\S/.test(line)) {
      const m = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
      if (!m) continue;
      const key = m[1]!;
      const val = m[2] ?? '';
      if (key === 'metadata') { inMeta = true; continue; }
      inMeta = false;
      top[key] = stripQuotes(val);
    } else if (inMeta) {
      const m = line.match(/^\s+([A-Za-z0-9_-]+):\s*(.*)$/);
      if (!m) continue;
      const key = m[1]!;
      const val = m[2] ?? '';
      meta[key] = stripQuotes(val);
    }
  }
  const body = lines.slice(end + 1).join('\n').trim();
  return { top, meta, body };
}

function parseMemoryFile(raw: string, fallbackName: string): ParsedMemoryFile {
  const { top, meta, body } = parseFrontmatter(raw);
  const name = top.name || fallbackName;
  const description = top.description || '';
  const type = meta.type || top.type || '';
  const project = meta.project || top.project || undefined;
  return { name, description, type, project, body };
}

function mapType(rawType: string, log: (msg: string) => void): string {
  const mapped = AUTO_MEMORY_TYPE_MAP[rawType];
  if (mapped) return mapped;
  log(`memory-inbox: unrecognized auto-memory type ${JSON.stringify(rawType)}, mapping to closest graph type ${JSON.stringify(AUTO_MEMORY_TYPE_FALLBACK)}`);
  return AUTO_MEMORY_TYPE_FALLBACK;
}

// [[wikilink]] -> candidate node name (verbatim; remember's own slugify does the normalizing)
function extractWikilinks(body: string): string[] {
  const out = new Set<string>();
  const re = /\[\[([^\]|#]+)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(body))) out.add(m[1]!.trim());
  return [...out];
}

// ---------- HTTP client for this server's own remember route ----------
export interface RememberFn {
  (body: unknown): Promise<{ ok: boolean; status: number; json: unknown }>;
}

function makeHttpRemember(): RememberFn {
  const url = `http://127.0.0.1:${config.port}/api/memory/remember`;
  return async (body: unknown) => {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify(body),
    });
    let json: unknown = null;
    try { json = await res.json(); } catch { /* non-json body: leave json null */ }
    return { ok: res.ok, status: res.status, json };
  };
}

export interface DrainDeps {
  remember: RememberFn;
  log?: (msg: string) => void;
}

/**
 * Drain one file: parse, remember the node (+ observation), then attempt one RELATES_TO edge
 * per wikilink (each its own remember call, since a missing target must skip only that edge,
 * never abort the node write — see api.ts's "no node named ... remember it first" 404).
 * Returns true if the node write itself succeeded (caller deletes the file), false to retry it
 * later (caller leaves the file and has already logged once).
 */
export async function drainFile(filePath: string, deps: DrainDeps): Promise<boolean> {
  const log = deps.log ?? console.error;
  const base = path.basename(filePath);
  let raw: string;
  try {
    raw = fs.readFileSync(filePath, 'utf8');
  } catch (e) {
    log(`memory-inbox: could not read ${base}: ${String(e)}`);
    return false;
  }

  const fallbackName = base.replace(/\.md$/i, '');
  const parsed = parseMemoryFile(raw, fallbackName);
  const type = mapType(parsed.type, log);
  const text = [parsed.description, parsed.body].filter((s) => s && s.trim().length).join('\n\n');

  const node: Record<string, unknown> = { name: parsed.name, type };
  if (parsed.project) node.project = parsed.project;
  const nodeResult = await safeRemember(deps.remember, { node, observations: text ? [text] : [] }, log, base);
  if (!nodeResult.ok) {
    log(`memory-inbox: remember failed for ${base} (status ${nodeResult.status}): ${JSON.stringify(nodeResult.json)}`);
    return false;
  }

  for (const linkName of extractWikilinks(parsed.body)) {
    const edgeResult = await safeRemember(
      deps.remember,
      { node, edges: [{ to: linkName, relation: 'RELATES_TO' }] },
      log,
      base,
    );
    if (!edgeResult.ok) {
      // a missing target (404) is the expected/documented skip case; anything else is still
      // just logged — the node itself already landed, so the file is still drained
      if (edgeResult.status === 404) {
        log(`memory-inbox: ${base} links [[${linkName}]] but no such node exists yet, skipping edge`);
      } else {
        log(`memory-inbox: edge [[${linkName}]] on ${base} failed (status ${edgeResult.status}): ${JSON.stringify(edgeResult.json)}`);
      }
    }
  }

  return true;
}

async function safeRemember(
  remember: RememberFn,
  body: unknown,
  log: (msg: string) => void,
  base: string,
): Promise<{ ok: boolean; status: number; json: unknown }> {
  try {
    return await remember(body);
  } catch (e) {
    log(`memory-inbox: remember call errored for ${base}: ${String(e)}`);
    return { ok: false, status: 0, json: null };
  }
}

function listMdFiles(dir: string): string[] {
  try {
    return fs.readdirSync(dir)
      .filter((f) => f.toLowerCase().endsWith('.md') && f !== MEMORY_INDEX_FILE);
  } catch {
    return [];
  }
}

/**
 * Scan the inbox directory once: drain every *.md file present (except MEMORY.md), deleting
 * on success and leaving+logging on failure. Used both at boot (files that landed while the
 * server was down) and as the debounce tick behind the fs.watch below.
 */
export async function scanOnce(dir: string, deps: DrainDeps): Promise<void> {
  for (const f of listMdFiles(dir)) {
    const full = path.join(dir, f);
    if (!fs.existsSync(full)) continue; // raced with a delete between listing and draining
    const ok = await drainFile(full, deps);
    if (ok) {
      try { fs.unlinkSync(full); } catch (e) { (deps.log ?? console.error)(`memory-inbox: drained ${f} but could not delete it: ${String(e)}`); }
    }
  }
}

/**
 * Start watching config.memoryInboxDir. Creates the directory if missing, does one boot scan
 * for files that arrived while nothing was watching, then debounces fs.watch events into
 * further scans. Returns a stop() to close the watcher (tests only; the live server never
 * calls it).
 */
export function startMemoryInboxWatcher(dir: string = config.memoryInboxDir, deps: DrainDeps = { remember: makeHttpRemember() }): { stop: () => void } {
  fs.mkdirSync(dir, { recursive: true });

  let timer: ReturnType<typeof setTimeout> | null = null;
  const DEBOUNCE_MS = 300;
  const scheduleScan = () => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(() => {
      timer = null;
      scanOnce(dir, deps).catch((e) => (deps.log ?? console.error)(`memory-inbox: scan failed: ${String(e)}`));
    }, DEBOUNCE_MS);
    timer.unref?.();
  };

  // boot scan: don't wait on the debounce for files that are already sitting there
  scanOnce(dir, deps).catch((e) => (deps.log ?? console.error)(`memory-inbox: boot scan failed: ${String(e)}`));

  const watcher = fs.watch(dir, { persistent: false }, () => scheduleScan());
  watcher.on('error', (e) => (deps.log ?? console.error)(`memory-inbox: watcher error: ${String(e)}`));

  return {
    stop: () => {
      if (timer) clearTimeout(timer);
      watcher.close();
    },
  };
}
